"""The "Annotate" tab: filament tracing, instance editing and per-instance browsing for the active layer.

- Filament layers (and their control layers) get the tracer panel: click control points in 2D, the centreline is
  regenerated by copick core after every edit; New / Reverse / Delete / Convert / Save.
- Instance segmentation layers get the instance editor: paint / erase / fill / pick instance IDs, new ID, recount,
  merge and delete (undoable), save.
- Picks layers can be coloured by instance; panoptic segment layers are browsable.
- The shared instance browser lists the active layer's instances: step, focus, show / hide / isolate.
"""

