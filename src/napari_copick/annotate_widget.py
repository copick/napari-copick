    # -- layers of a session ---------------------------------------------------------------------------------------

    def _session_layers(self, session: FilamentEditSession, kind: str):
        for layer in self.viewer.layers:
            if layer.metadata.get(SESSION_KEY) is session and layer.metadata.get(KIND_KEY) == kind:
                return layer
        return None

    def centreline_layer(self, session: FilamentEditSession):
        return self._session_layers(session, CENTRELINE_KIND)

    def controls_layer(self, session: FilamentEditSession):
        return self._session_layers(session, CONTROLS_KIND)

    def start_editing(self, session: FilamentEditSession) -> None:
        """Show the control layer of a session and switch it to add mode."""
        centreline = self.centreline_layer(session)
        if centreline is None:
            centreline = add_centreline_layer(self.viewer, session)
        controls = self.controls_layer(session)
        if controls is None:
            controls = add_controls_layer(self.viewer, session)
            sync = ControlLayerSync(controls, centreline, session, on_change=lambda msg: self._after_sync(session, msg))
            controls.events.data.connect(sync.on_data_event)
            self._syncs[id(session)] = (sync, controls)
            self._bind_keys(controls)
        if self.viewer.dims.ndisplay != 2:
            self.plugin.info_label.setText("Switch to the 2D view to place control points.")
        self.viewer.layers.selection.active = controls
        controls.mode = "add"

    def stop_editing(self, session: FilamentEditSession) -> None:
        controls = self.controls_layer(session)
        if controls is not None:
            self.viewer.layers.remove(controls)
        centreline = self.centreline_layer(session)
        if centreline is not None:
            self.viewer.layers.selection.active = centreline

    def _bind_keys(self, layer: Points) -> None:
        bindings = {
            "Shift-N": lambda _layer: self.tracer.new_filament(),
            "Shift-R": lambda _layer: self.tracer.reverse(self.tracer.active_spin.value()),
            "Shift-D": lambda _layer: self.tracer.delete([self.tracer.active_spin.value()]),
            "Shift-]": lambda _layer: self.tracer.step(1),
            "Shift-[": lambda _layer: self.tracer.step(-1),
        }
        for key, func in bindings.items():
            try:
                layer.bind_key(key, func, overwrite=True)
            except Exception as e:  # pragma: no cover - depends on the napari version
                logger.warning(f"Could not bind {key}: {e}")

    def _after_sync(self, session: FilamentEditSession, message: str) -> None:
        if message:
            self.plugin.info_label.setText(message)
        self.tracer.update_state()
        self.refresh()

    def after_session_edit(self, session: FilamentEditSession, focus: bool = False) -> None:
        """Redraw a session's layers after an edit made through the panel or browser."""
        entry = self._syncs.get(id(session))
        if entry is not None and entry[1] in self.viewer.layers:
            entry[0].redraw()
        else:
            centreline = self.centreline_layer(session)
            if centreline is not None:
                from napari_copick.filament_layers import refresh_centreline_layer

                refresh_centreline_layer(centreline, session)
        self.tracer.update_state()
        self.refresh()
        if focus and isinstance(self._adapter, FilamentsAdapter):
            self._adapter.focus(session.active_id)

    # -- starting new annotations ----------------------------------------------------------------------------------

    def _new_dialog(self, kind: str):
        if self.plugin.root is None:
            self.plugin.info_label.setText("Load a configuration first.")
            return None
        if not _tomogram_layers(self.viewer):
            self.plugin.info_label.setText("Open a tomogram first (the new annotation uses its run and voxel spacing).")
            return None
        sm = self.plugin.save_manager
        dlg = _NewAnnotationDialog(
            self,
            self.viewer,
            self.plugin.root,
            kind,
            sm._last_user_id or "napari",
            sm._last_session_id or "manual",
        )
        if dlg.exec_() != QDialog.Accepted:
            return None
        return dlg.values()

    def new_trace(self) -> None:
        values = self._new_dialog("filaments")
        if values is None:
            return
        tomo_layer, obj, user_id, session_id = values
        vs = tomo_layer.metadata["copick_voxel_spacing"]
        session = FilamentEditSession(vs.run, obj.name, user_id, session_id, step=vs.voxel_size)
        add_centreline_layer(self.viewer, session)
        self.start_editing(session)
        self.tracer.set_session(session)
        self.stack.setCurrentWidget(self.tracer)

    def open_filaments(self, copick_filaments: Any) -> None:
        """Load a filament set (if not loaded) and start editing it."""
        for layer in self.viewer.layers:
            if layer.metadata.get("copick_filaments") is copick_filaments:
                self.start_editing(layer.metadata[SESSION_KEY])
                return
        session = FilamentEditSession.from_filaments(copick_filaments, step=copick_filaments.voxel_spacing or 10.0)
        layer = add_centreline_layer(self.viewer, session, run=copick_filaments.run)
        layer.metadata["copick_filaments"] = copick_filaments
        self.start_editing(session)

    def new_instance_segmentation(self) -> None:
        values = self._new_dialog("instance")
        if values is None:
            return
        tomo_layer, obj, user_id, session_id = values
        shape = tomo_layer.data.shape[-3:]
        layer = self.viewer.add_labels(
            np.zeros(shape, dtype=np.uint16),
            name=f"Instances: {obj.name} ({user_id} | {session_id}) (new)",
            scale=tomo_layer.scale[-3:],
        )
        vs = tomo_layer.metadata["copick_voxel_spacing"]
        layer.metadata.update(
            {
                "copick_run": vs.run,
                "copick_voxel_size": vs.voxel_size,
                "copick_resolution_level": tomo_layer.metadata.get("copick_resolution_level", 0),
                "copick_source_object_name": obj.name,
                SEGMENTATION_TYPE_KEY: "instance",
                COUNTS_KEY: {},
                BBOXES_KEY: {},
            },
        )
        layer.colormap = instance_colormap([1])
        layer.metadata["copick_extra_ids"] = {1}
        layer.selected_label = 1
        layer.mode = "paint"
        self.viewer.layers.selection.active = layer

    # -- active layer ----------------------------------------------------------------------------------------------

    def _on_layer_removed(self, event: Any) -> None:
        layer = getattr(event, "value", None)
        session = layer.metadata.get(SESSION_KEY) if layer is not None else None
        if session is not None and layer.metadata.get(KIND_KEY) == CONTROLS_KIND:
            self._syncs.pop(id(session), None)
            if self.tracer.session is session:
                self.tracer.edit_btn.blockSignals(True)
                self.tracer.edit_btn.setChecked(False)
                self.tracer.edit_btn.blockSignals(False)
        if self._adapter is not None and self._adapter.layer is layer:
            self._adapter = None
            self._on_active_layer()

    def _on_active_layer(self, *_args) -> None:
        layer = self.viewer.layers.selection.active
        session = layer.metadata.get(SESSION_KEY) if layer is not None else None
        if session is not None:
            centreline = self.centreline_layer(session)
            self._adapter = FilamentsAdapter(centreline, self.viewer) if centreline is not None else None
            self.tracer.set_session(session)
            self.stack.setCurrentWidget(self.tracer)
        else:
            self._adapter = adapter_for(layer, self.viewer)
            if isinstance(self._adapter, LabelsAdapter):
                self.editor.set_layer(layer)
                self.stack.setCurrentWidget(self.editor)
            else:
                self.stack.setCurrentWidget(self.empty)
        self.active_label.setText(f"Active layer: <b>{layer.name}</b>" if layer is not None else "No active layer")
        caps = dict(self._adapter.capabilities) if self._adapter is not None else {}
        self.browser.set_capabilities(**caps)
        if isinstance(self._adapter, PointsAdapter):
            self.browser.set_color_by_instance(layer.metadata.get("copick_color_mode") == "instance")
        self.refresh(reset=True)

    def refresh(self, reset: bool = False) -> None:
        if self._adapter is None:
            self.browser.set_title("Instances")
            self.browser.clear()
            return
        self.browser.set_title(self._adapter.title)
        if reset:
            self.browser.clear()
        self.browser.set_rows(self._adapter.rows(), kind=self._adapter.kind)

    # -- browser actions -------------------------------------------------------------------------------------------

    def _on_browser_current(self, key: int) -> None:
        if isinstance(self._adapter, FilamentsAdapter):
            self.tracer.active_spin.setValue(key)
        elif isinstance(self._adapter, LabelsAdapter):
            self.editor.id_spin.setValue(key)

    def _on_browser_focus(self, key: int) -> None:
        if self._adapter is not None:
            self._adapter.focus(key)

    def _on_browser_visibility(self, keys) -> None:
        if self._adapter is not None:
            self._adapter.set_visible(set(keys))

    def _on_browser_new(self) -> None:
        if isinstance(self._adapter, FilamentsAdapter):
            self.tracer.new_filament()
        elif isinstance(self._adapter, LabelsAdapter):
            self.editor.new_id()

    def _on_browser_delete(self, keys) -> None:
        if not keys:
            return
        reply = QMessageBox.question(
            self,
            "Delete instances",
            f"Delete {len(keys)} instance(s)? (Instance segmentation edits can be undone with Ctrl-Z.)",
            QMessageBox.Yes | QMessageBox.No,
            QMessageBox.No,
        )
        if reply != QMessageBox.Yes:
            return
        if isinstance(self._adapter, FilamentsAdapter):
            self.tracer.delete(keys)
        elif isinstance(self._adapter, LabelsAdapter):
            self.editor.relabel(keys, 0)

    def _on_browser_merge(self, sources, target: int) -> None:
        if isinstance(self._adapter, LabelsAdapter):
            self.editor.relabel(sources, target)
        elif isinstance(self._adapter, FilamentsAdapter):
            self.tracer.join([target, *sources], target)

    def _on_browser_reverse(self, key: int) -> None:
        if isinstance(self._adapter, FilamentsAdapter):
            self.tracer.reverse(key)

    def _on_color_toggle(self, on: bool) -> None:
        if isinstance(self._adapter, PointsAdapter):
            self._adapter.set_color_by_instance(on)
