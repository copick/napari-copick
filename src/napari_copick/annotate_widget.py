@thread_worker
def _label_stats_worker(data: np.ndarray):
    return {"counts": label_counts(data), "bboxes": label_bboxes(data)}


@thread_worker
def _label_indices_worker(data: np.ndarray, ids):
    return np.nonzero(np.isin(data, list(ids)))


def _tomogram_layers(viewer: Any):
    return [layer for layer in viewer.layers if isinstance(layer, Image) and "copick_tomogram" in layer.metadata]


class _NewAnnotationDialog(QDialog):
    """Choose run (from an open tomogram), object, user and session for a new filament set or instance seg."""

    def __init__(self, parent: Any, viewer: Any, root: Any, kind: str, user_id: str, session_id: str):
        super().__init__(parent)
        self.setWindowTitle("New filament trace" if kind == "filaments" else "New instance segmentation")
        form = QFormLayout(self)
        self.tomo_combo = QComboBox()
        for layer in _tomogram_layers(viewer):
            self.tomo_combo.addItem(layer.name, layer)
        form.addRow("Tomogram:", self.tomo_combo)
        self.object_combo = QComboBox()
        for obj in root.pickable_objects:
            if kind == "filaments" and not is_filament_object(obj):
                continue
            self.object_combo.addItem(obj.name, obj)
        form.addRow("Object:", self.object_combo)
        self.user_input = QLineEdit(user_id)
        form.addRow("User ID:", self.user_input)
        self.session_input = QLineEdit(session_id)
        form.addRow("Session ID:", self.session_input)
        if kind == "filaments" and self.object_combo.count() == 0:
            note = QLabel("No filament objects. Declare one with ✏️ Edit Objects (check 'Is Filament').")
            note.setWordWrap(True)
            form.addRow(note)
        buttons = QDialogButtonBox(QDialogButtonBox.Ok | QDialogButtonBox.Cancel)
        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)
        form.addRow(buttons)
        ok = self.tomo_combo.count() > 0 and self.object_combo.count() > 0
        buttons.button(QDialogButtonBox.Ok).setEnabled(ok)

    def values(self) -> Tuple[Any, Any, str, str]:
        return (
            self.tomo_combo.currentData(),
            self.object_combo.currentData(),
            self.user_input.text().strip() or "napari",
            self.session_input.text().strip() or "manual",
        )


