    # -- binding ---------------------------------------------------------------------------------------------------

    def set_session(self, session: FilamentEditSession) -> None:
        self.session = session
        self.edit_btn.blockSignals(True)
        self.edit_btn.setChecked(self.annotate.controls_layer(session) is not None)
        self.edit_btn.blockSignals(False)
        self.update_state()

    def update_state(self) -> None:
        s = self.session
        if s is None:
            return
        read_only = s.read_only
        n = len(s.to_list())
        dirty = " · unsaved changes" if s.dirty else ""
        note = " · read-only source (save under a user session)" if read_only else ""
        self.info.setText(
            f"<b>{s.object_name}</b> ({s.user_id} | {s.session_id}) · run {s.run.name} · {n} filaments · "
            f"step {s.step:g} Å{dirty}{note}",
        )
        self.active_spin.blockSignals(True)
        self.active_spin.setValue(s.active_id)
        self.active_spin.blockSignals(False)
        self.mode_combo.blockSignals(True)
        self.mode_combo.setCurrentIndex(max(0, self.mode_combo.findData(s.insert_mode)))
        self.mode_combo.blockSignals(False)
        kind = s.kind(s.active_id)
        self.convert_btn.setVisible(kind == "bspline")

    # -- actions ---------------------------------------------------------------------------------------------------

    def _on_active_changed(self, value: int) -> None:
        if self.session is not None:
            self.session.active_id = int(value)
            controls = self.annotate.controls_layer(self.session)
            if controls is not None:
                controls.feature_defaults = {"instance_id": int(value), "order": -1}
            self.update_state()
            self.annotate.browser.set_current(int(value), emit=False)

    def _on_mode_changed(self, mode: str) -> None:
        if self.session is not None:
            self.session.insert_mode = mode

    def _on_edit_toggled(self, on: bool) -> None:
        if self.session is None:
            return
        if on:
            self.annotate.start_editing(self.session)
        else:
            self.annotate.stop_editing(self.session)

    def new_filament(self) -> None:
        if self.session is None:
            return
        self.session.new_filament()
        self.annotate.after_session_edit(self.session)

    def reverse(self, instance_id: int) -> None:
        if self.session is None:
            return
        self.session.reverse(instance_id)
        self.annotate.after_session_edit(self.session)

    def join(self, ids, target: int) -> None:
        if self.session is None:
            return
        try:
            self.session.join(ids, target=target)
        except ValueError as e:
            logger.warning(str(e))
            return
        self.annotate.after_session_edit(self.session)

    def delete(self, ids) -> None:
        if self.session is None:
            return
        for i in ids:
            self.session.delete_filament(int(i))
        self.annotate.after_session_edit(self.session)

    def convert_active(self) -> None:
        if self.session is None:
            return
        self.session.convert_to_catmull_rom(self.session.active_id)
        self.annotate.after_session_edit(self.session)

    def step(self, delta: int) -> None:
        if self.session is None:
            return
        ids = self.session.ids()
        if not ids:
            return
        i = ids.index(self.session.active_id) if self.session.active_id in ids else -1
        self.session.active_id = ids[(i + delta) % len(ids)]
        self.annotate.after_session_edit(self.session, focus=True)

    def save(self) -> None:
        if self.session is None:
            return
        layer = self.annotate.centreline_layer(self.session) or self.annotate.controls_layer(self.session)
        self.annotate.plugin.save_manager.open_save_filaments_dialog(preset_layer=layer)


