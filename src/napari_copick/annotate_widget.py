    def set_layer(self, layer: Labels) -> None:
        if self.layer is not None:
            try:
                self.layer.events.selected_label.disconnect(self._sync_from_layer)
                self.layer.events.mode.disconnect(self._sync_from_layer)
            except (TypeError, ValueError, RuntimeError):
                pass
        self.layer = layer
        layer.events.selected_label.connect(self._sync_from_layer)
        layer.events.mode.connect(self._sync_from_layer)
        self._sync_from_layer()

    def _sync_from_layer(self, *_args) -> None:
        layer = self.layer
        if layer is None:
            return
        meta = layer.metadata
        counts = meta.get(COUNTS_KEY, {})
        level = meta.get("copick_resolution_level", 0) or 0
        obj = meta.get("copick_source_object_name", "?")
        seg = meta.get("copick_segmentation")
        origin = f"{seg.user_id} | {seg.session_id}" if seg is not None else "new, unsaved"
        self.info.setText(f"<b>{obj}</b> ({origin}) · {len(counts)} instances · {layer.data.dtype}")
        self.warning.setText(
            (
                f"Loaded at resolution level {level}: saving upsamples it to full resolution with nearest-neighbour "
                "interpolation, so painted edges come out blocky. Load level 0 to edit at full resolution."
                if level
                else ""
            ),
        )
        self.warning.setVisible(bool(level))
        for w, v in ((self.id_spin, int(layer.selected_label)), (self.brush_spin, int(layer.brush_size))):
            w.blockSignals(True)
            w.setValue(v)
            w.blockSignals(False)
        self.preserve_cb.blockSignals(True)
        self.preserve_cb.setChecked(bool(layer.preserve_labels))
        self.preserve_cb.blockSignals(False)
        mode = str(getattr(layer.mode, "value", layer.mode))
        for b in self.mode_group.buttons():
            b.setChecked(b.property("mode") == mode)

    def _on_id_changed(self, value: int) -> None:
        if self.layer is not None:
            self._ensure_capacity(value)
            self.layer.selected_label = int(value)
            self._ensure_colored(int(value))
            self.annotate.browser.set_current(int(value), emit=False)

    def _on_brush_changed(self, value: int) -> None:
        if self.layer is not None:
            self.layer.brush_size = int(value)

    def _on_preserve_changed(self, on: bool) -> None:
        if self.layer is not None:
            self.layer.preserve_labels = bool(on)

    def _set_mode(self, mode: str) -> None:
        if self.layer is not None:
            self.layer.mode = mode

    def _ensure_capacity(self, value: int) -> None:
        """Instance IDs above 65535 need a uint32 volume."""
        layer = self.layer
        dtype = layer.data.dtype
        if dtype.kind in "ui" and value > np.iinfo(dtype).max:
            layer.data = layer.data.astype(np.uint32)

    def _ensure_colored(self, value: int) -> None:
        counts = self.layer.metadata.setdefault(COUNTS_KEY, {})
        known = set(counts) | self.layer.metadata.setdefault("copick_extra_ids", set())
        if value > 0 and value not in known:
            self.layer.metadata["copick_extra_ids"].add(value)
            ids = set(counts) | self.layer.metadata["copick_extra_ids"]
            self.layer.colormap = instance_colormap(ids, self.layer.metadata.get("copick_hidden_ids", ()))

    def new_id(self) -> None:
        if self.layer is None:
            return
        counts = self.layer.metadata.get(COUNTS_KEY, {})
        value = next_instance_id(counts.keys(), self.layer.metadata.get("copick_extra_ids", set()))
        self.id_spin.setValue(value)
        self._set_mode("paint")

    def recount(self) -> None:
        layer = self.layer
        if layer is None:
            return
        worker = _label_stats_worker(np.asarray(layer.data))

        def done(result: Dict[str, Any]) -> None:
            layer.metadata[COUNTS_KEY] = result["counts"]
            layer.metadata[BBOXES_KEY] = result["bboxes"]
            layer.metadata["copick_extra_ids"] = set()
            layer.colormap = instance_colormap(result["counts"].keys(), layer.metadata.get("copick_hidden_ids", ()))
            self._sync_from_layer()
            self.annotate.refresh()

        worker.returned.connect(done)
        worker.start()

    def relabel(self, ids, value: int) -> None:
        """Set ``ids`` to ``value`` (0 deletes) through the layer, so the edit can be undone."""
        layer = self.layer
        if layer is None:
            return
        worker = _label_indices_worker(np.asarray(layer.data), ids)

        def done(indices) -> None:
            if len(indices[0]):
                layer.data_setitem(indices, value)
            self.recount()

        worker.returned.connect(done)
        worker.start()

    def save(self) -> None:
        if self.layer is not None:
            self.annotate.viewer.layers.selection.active = self.layer
            self.annotate.plugin.save_manager.open_save_segmentation_dialog()


